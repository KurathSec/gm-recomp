//! Corpus-wide Markdown report: games, shared runner builds, and the union of
//! Windows APIs the HLE layer has to provide (static, delay-load and dynamic).

use anyhow::Result;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn load_manifests(out: &Path) -> Result<Vec<Value>> {
    let mut v = Vec::new();
    let mut dirs: Vec<_> = fs::read_dir(out)?.flatten().map(|e| e.path()).collect();
    dirs.sort();
    for d in dirs {
        let m = d.join("manifest.json");
        if m.is_file() {
            v.push(serde_json::from_str(&fs::read_to_string(m)?)?);
        }
    }
    Ok(v)
}

fn s(v: &Value) -> &str {
    v.as_str().unwrap_or("")
}

fn engine_label(e: &Value) -> String {
    match s(&e["kind"]) {
        "gm80" => "GM8.0".into(),
        "gm81" => "GM8.1".into(),
        "gm8" => "GM8 (other build)".into(),
        "gms" => {
            let ver: Vec<String> = e["version"].as_array().map(|a| a.iter().map(|x| x.to_string()).collect()).unwrap_or_default();
            format!(
                "GMS {} bc{} {}",
                ver.join("."),
                e["bytecode"],
                if e["yyc"].as_bool() == Some(true) { "YYC" } else { "VM" }
            )
        }
        other => other.to_owned(),
    }
}

pub fn write(out: &Path, md: &Path) -> Result<()> {
    let games = load_manifests(out)?;
    let mut r = String::new();
    writeln!(r, "# Corpus inventory\n\nGenerated by `importer report` from {} imported games.\n", games.len())?;

    writeln!(r, "## Games\n\n| slug | engine | entry | PE modules | packer hints |\n|---|---|---|---|---|")?;
    for g in &games {
        let mods = g["modules"].as_array().cloned().unwrap_or_default();
        let hints: Vec<String> = mods
            .iter()
            .flat_map(|m| {
                let p = s(&m["path"]).to_owned();
                m["packer_hints"].as_array().cloned().unwrap_or_default().into_iter().map(move |h| format!("{p}: {}", s(&h)))
            })
            .collect();
        writeln!(
            r,
            "| {} | {} | `{}` | {} | {} |",
            s(&g["slug"]),
            engine_label(&g["engine"]),
            s(&g["entry"]),
            mods.len(),
            if hints.is_empty() { "-".into() } else { hints.join("<br>") }
        )?;
    }

    // Identical code sections across games mean one recompilation serves them all.
    let mut by_code: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut module_info: BTreeMap<String, (u64, String)> = BTreeMap::new();
    for g in &games {
        for m in g["modules"].as_array().into_iter().flatten() {
            let key = s(&m["code_sha256"]).to_owned();
            by_code.entry(key.clone()).or_default().push(format!("{}/{}", s(&g["slug"]), s(&m["path"])));
            let exec: u64 = m["sections"]
                .as_array()
                .into_iter()
                .flatten()
                .filter(|x| x["exec"].as_bool() == Some(true))
                .map(|x| x["virtual_size"].as_u64().unwrap_or(0))
                .sum();
            module_info.insert(key, (exec, if m["relocs_stripped"].as_bool() == Some(true) { "stripped".into() } else { "present".into() }));
        }
    }
    writeln!(r, "\n## Distinct code images\n\n| code sha256 | exec bytes | relocs | used by |\n|---|---|---|---|")?;
    for (hash, users) in &by_code {
        let (exec, relocs) = &module_info[hash];
        writeln!(r, "| `{}` | {} | {} | {} |", &hash[..12], exec, relocs, users.join("<br>"))?;
    }

    // Static code discovery results, when `importer discover` has run.
    let mut disc_rows = Vec::new();
    for g in &games {
        let path = out.join(s(&g["slug"])).join("discovery.json");
        let Ok(text) = fs::read_to_string(&path) else { continue };
        let d: Value = serde_json::from_str(&text)?;
        for (module, v) in d.as_object().into_iter().flatten() {
            let exec = v["exec_bytes"].as_f64().unwrap_or(0.0).max(1.0);
            let pct = |k: &str| 100.0 * v[k].as_f64().unwrap_or(0.0) / exec;
            disc_rows.push(format!(
                "| {} | {} | {} | {:.1}% | {:.1}% | {} | {} | {} | {} | {} |",
                s(&g["slug"]),
                module,
                v["exec_bytes"].as_u64().unwrap_or(0) / 1024,
                pct("strong_bytes"),
                pct("total_bytes"),
                v["functions"],
                v["jump_tables"].as_array().map_or(0, |a| a.len()),
                v["unresolved_indirect_jumps"],
                v["gap_count"],
                v["gap_bytes"].as_u64().unwrap_or(0) / 1024,
            ));
        }
    }
    if !disc_rows.is_empty() {
        writeln!(r, "\n## Static code discovery\n\n`strong` = reached from entry/exports/relocations/direct calls/jump tables; `total` adds pointer-scan and prologue heuristics. Gaps exclude padding.\n")?;
        writeln!(r, "| game | module | exec KB | strong | total | functions | jump tables | unresolved jmp | gaps | gap KB |\n|---|---|---|---|---|---|---|---|---|---|")?;
        for row in disc_rows {
            writeln!(r, "{row}")?;
        }
    }

    // dll -> function -> (kind, users)
    let mut apis: BTreeMap<String, BTreeMap<String, (BTreeSet<&'static str>, BTreeSet<String>)>> = BTreeMap::new();
    for g in &games {
        for m in g["modules"].as_array().into_iter().flatten() {
            let user = s(&m["path"]).rsplit('/').next().unwrap_or("").to_lowercase();
            for imp in m["imports"].as_array().into_iter().flatten() {
                let kind = if imp["delay_load"].as_bool() == Some(true) { "delay" } else { "static" };
                for f in imp["functions"].as_array().into_iter().flatten() {
                    let e = apis.entry(s(&imp["dll"]).to_owned()).or_default().entry(s(f).to_owned()).or_default();
                    e.0.insert(kind);
                    e.1.insert(user.clone());
                }
            }
            for (dll, fns) in m["dynamic_api_candidates"].as_object().into_iter().flatten() {
                for f in fns.as_array().into_iter().flatten() {
                    let e = apis.entry(dll.clone()).or_default().entry(s(f).to_owned()).or_default();
                    e.0.insert("dynamic?");
                    e.1.insert(user.clone());
                }
            }
        }
    }
    let total: usize = apis.values().map(|f| f.len()).sum();
    writeln!(r, "\n## API surface\n\n{} functions across {} DLLs. `dynamic?` = name found as a string next to a dynamically loaded DLL (likely `GetProcAddress`).\n", total, apis.len())?;
    writeln!(r, "| dll | functions |\n|---|---|")?;
    for (dll, fns) in &apis {
        writeln!(r, "| {dll} | {} |", fns.len())?;
    }
    for (dll, fns) in &apis {
        writeln!(r, "\n### {dll}\n\n| function | kind | used by |\n|---|---|---|")?;
        for (f, (kinds, users)) in fns {
            writeln!(
                r,
                "| {f} | {} | {} |",
                kinds.iter().copied().collect::<Vec<_>>().join(", "),
                users.iter().cloned().collect::<Vec<_>>().join(", ")
            )?;
        }
    }
    if let Some(parent) = md.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(md, r)?;
    println!("wrote {}", md.display());
    Ok(())
}
